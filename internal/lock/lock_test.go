const sha = "fae2a30c1d4b8e9f0a2b3c4d5e6f708192a3b4c5"

const populated = `# graft.lock — generated by ` + "`graft sync`" + `. Do not edit.
version = 1

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"

  [[source.item]]
  id    = "agent:apply-orchestrator"
  files = [".claude/agents/apply-orchestrator.md"]

  [[source.item]]
  id    = "schema:tdd"
  files = [
    "openspec/schemas/tdd/schema.yaml",
    "openspec/schemas/tdd/templates/design.md",
  ]
`

// oneSource renders a lock holding a single source with the given extra body lines,
// so a table case names only what it is testing.
func oneSource(body string) string {
	return `version = 1

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"
` + body
}

func entries(t *testing.T, dir string) []string {
	t.Helper()
	des, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("reading %s: %v", dir, err)
	}
	names := make([]string, 0, len(des))
	for _, de := range des {
		names = append(names, de.Name())
	}
	return names
}

func TestLoad_Absent(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "graft.toml"), []byte(""), 0o600); err != nil {
		t.Fatalf("writing fixture: %v", err)
	}

	l, err := lock.Load(filepath.Join(dir, "graft.lock"))
	if err != nil {
		t.Fatalf("Load() error = %v, want nil", err)
	}
	if l.Version != 1 {
		t.Errorf("Version = %d, want 1", l.Version)
	}
	if len(l.Sources) != 0 {
		t.Errorf("len(Sources) = %d, want 0", len(l.Sources))
	}
	if got := entries(t, dir); len(got) != 1 || got[0] != "graft.toml" {
		t.Errorf("tree = %v, want only graft.toml — no graft.lock may be created", got)
	}
}

