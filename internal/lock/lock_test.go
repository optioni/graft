func TestParse_Populated(t *testing.T) {
	t.Parallel()

	l, err := lock.Parse([]byte(populated), "graft.lock")
	if err != nil {
		t.Fatalf("Parse() error = %v, want nil", err)
	}
	if len(l.Sources) != 1 {
		t.Fatalf("len(Sources) = %d, want 1", len(l.Sources))
	}
	s := l.Sources[0]
	if s.Name != "openspec-schemas" {
		t.Errorf("Name = %q, want %q", s.Name, "openspec-schemas")
	}
	if s.Git != "github.com/optioni/openspec-schemas" {
		t.Errorf("Git = %q, want %q", s.Git, "github.com/optioni/openspec-schemas")
	}
	if s.Rev != "v1.2.0" {
		t.Errorf("Rev = %q, want %q", s.Rev, "v1.2.0")
	}
	if s.Resolved != sha {
		t.Errorf("Resolved = %q, want %q", s.Resolved, sha)
	}
	if len(s.Items) != 2 {
		t.Fatalf("len(Items) = %d, want 2", len(s.Items))
	}
	want := map[string][]string{
		"agent:apply-orchestrator": {".claude/agents/apply-orchestrator.md"},
		"schema:tdd": {
			"openspec/schemas/tdd/schema.yaml",
			"openspec/schemas/tdd/templates/design.md",
		},
	}
	for _, it := range s.Items {
		w, ok := want[it.ID]
		if !ok {
			t.Errorf("unexpected item %q", it.ID)
			continue
		}
		if strings.Join(it.Files, "\n") != strings.Join(w, "\n") {
			t.Errorf("item %q files = %v, want %v", it.ID, it.Files, w)
		}
	}
}

