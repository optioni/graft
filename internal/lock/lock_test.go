func TestParse_VersionErrors(t *testing.T) {
	t.Parallel()

	for name, tc := range map[string]struct {
		in   string
		want string
	}{
		"missing version": {
			in: `[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"
`,
			want: `graft.lock: version is required`,
		},
		"newer version": {
			in: `version = 2

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"
`,
			want: `graft.lock: version 2 is not supported by this graft; upgrade graft`,
		},
		"version below one": {
			in:   "version = 0\n",
			want: `graft.lock: version 0 is not a known lock version`,
		},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			l, err := lock.Parse([]byte(tc.in), "graft.lock")
			if err == nil {
				t.Fatalf("Parse() error = nil, want %q", tc.want)
			}
			if got := err.Error(); got != tc.want {
				t.Errorf("Parse() error = %q, want %q", got, tc.want)
			}
			if l != nil {
				t.Errorf("Parse() lock = %+v, want nil — no source may be returned", l)
			}
		})
	}
}

func TestParse_SourceErrors(t *testing.T) {
	t.Parallel()

	for name, tc := range map[string]struct {
		in   string
		want string
	}{
		"missing resolved": {
			in: `version = 1

[[source]]
name = "openspec-schemas"
git  = "github.com/optioni/openspec-schemas"
rev  = "v1.2.0"
`,
			want: `graft.lock: source "openspec-schemas": resolved is required`,
		},
		"malformed resolved": {
			in: `version = 1

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "v1.2.0"
`,
			want: `graft.lock: source "openspec-schemas": resolved "v1.2.0" is not a 40-character hex sha`,
		},
		"uppercase resolved": {
			in: `version = 1

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "FAE2A30C1D4B8E9F0A2B3C4D5E6F708192A3B4C5"
`,
			want: `graft.lock: source "openspec-schemas": resolved "FAE2A30C1D4B8E9F0A2B3C4D5E6F708192A3B4C5" is not a 40-character hex sha`,
		},
		"duplicate source": {
			in: `version = 1

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.3.0"
resolved = "` + sha + `"
`,
			want: `graft.lock: duplicate source "openspec-schemas"`,
		},
		"empty source name": {
			in: `version = 1

[[source]]
name     = ""
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"
`,
			want: `graft.lock: source name is empty`,
		},
		"missing git": {
			in: `version = 1

[[source]]
name     = "openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"
`,
			want: `graft.lock: source "openspec-schemas": git is required`,
		},
		"missing rev": {
			in: `version = 1

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
resolved = "` + sha + `"
`,
			want: `graft.lock: source "openspec-schemas": rev is required`,
		},
		"unknown source key": {
			in: `version = 1

[[source]]
name     = "openspec-schemas"
git      = "github.com/optioni/openspec-schemas"
rev      = "v1.2.0"
resolved = "` + sha + `"
sha      = "` + sha + `"
`,
			want: `graft.lock: source "openspec-schemas": unknown key "sha"`,
		},
		"unknown top-level key": {
			in:   "version = 1\nlockfile = true\n",
			want: `graft.lock: unknown key "lockfile"`,
		},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			l, err := lock.Parse([]byte(tc.in), "graft.lock")
			if err == nil {
				t.Fatalf("Parse() error = nil, want %q", tc.want)
			}
			if got := err.Error(); got != tc.want {
				t.Errorf("Parse() error = %q, want %q", got, tc.want)
			}
			if l != nil {
				t.Errorf("Parse() lock = %+v, want nil", l)
			}
		})
	}
}

func TestParse_ItemErrors(t *testing.T) {
	t.Parallel()

	for name, tc := range map[string]struct {
		body string
		want string
	}{
		"malformed item id": {
			body: `
  [[source.item]]
  id    = "tdd"
  files = []
`,
			want: `graft.lock: source "openspec-schemas": invalid item id "tdd": want kind:name`,
		},
		"duplicate item id": {
			body: `
  [[source.item]]
  id    = "schema:tdd"
  files = []

  [[source.item]]
  id    = "schema:tdd"
  files = []
`,
			want: `graft.lock: source "openspec-schemas": duplicate item "schema:tdd"`,
		},
		"unknown item key": {
			body: `
  [[source.item]]
  id     = "schema:tdd"
  files  = []
  hashes = []
`,
			want: `graft.lock: source "openspec-schemas": item "schema:tdd": unknown key "hashes"`,
		},
		"escaping file path": {
			body: `
  [[source.item]]
  id    = "schema:tdd"
  files = ["../outside.md"]
`,
			want: `graft.lock: source "openspec-schemas": item "schema:tdd": file "../outside.md" is not a relative path inside the repo`,
		},
		"absolute file path": {
			body: `
  [[source.item]]
  id    = "schema:tdd"
  files = ["/etc/passwd"]
`,
			want: `graft.lock: source "openspec-schemas": item "schema:tdd": file "/etc/passwd" is not a relative path inside the repo`,
		},
		"parent segment mid-path": {
			body: `
  [[source.item]]
  id    = "schema:tdd"
  files = ["openspec/../../outside.md"]
`,
			want: `graft.lock: source "openspec-schemas": item "schema:tdd": file "openspec/../../outside.md" is not a relative path inside the repo`,
		},
		"empty file path": {
			body: `
  [[source.item]]
  id    = "schema:tdd"
  files = [""]
`,
			want: `graft.lock: source "openspec-schemas": item "schema:tdd": file "" is not a relative path inside the repo`,
		},
		"duplicate file": {
			body: `
  [[source.item]]
  id    = "schema:tdd"
  files = [
    "openspec/schemas/tdd/schema.yaml",
    "openspec/schemas/tdd/schema.yaml",
  ]
`,
			want: `graft.lock: source "openspec-schemas": item "schema:tdd": duplicate file "openspec/schemas/tdd/schema.yaml"`,
		},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			l, err := lock.Parse([]byte(oneSource(tc.body)), "graft.lock")
			if err == nil {
				t.Fatalf("Parse() error = nil, want %q", tc.want)
			}
			if got := err.Error(); got != tc.want {
				t.Errorf("Parse() error = %q, want %q", got, tc.want)
			}
			if l != nil {
				t.Errorf("Parse() lock = %+v, want nil — no file list may be returned", l)
			}
		})
	}
}

func TestParse_ItemNoFiles(t *testing.T) {
	t.Parallel()

	in := oneSource(`
  [[source.item]]
  id    = "schema:tdd"
  files = []
`)
	l, err := lock.Parse([]byte(in), "graft.lock")
	if err != nil {
		t.Fatalf("Parse() error = %v, want nil", err)
	}
	if len(l.Sources) != 1 || len(l.Sources[0].Items) != 1 {
		t.Fatalf("Sources = %+v, want one source with one item", l.Sources)
	}
	if n := len(l.Sources[0].Items[0].Files); n != 0 {
		t.Errorf("len(Files) = %d, want 0", n)
	}
}

